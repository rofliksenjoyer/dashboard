def _metrics():
    return {m.code: m.id for m in Metric.query.all()}


def _company(short_name, country_code=None):
    q = Monopoly.query.filter_by(short_name=short_name)
    if country_code:
        c = Country.query.filter_by(code=country_code).first()
        if c:
            q = q.filter_by(country_id=c.id)
    return q.first()


def _replace_periods(monopoly, data):
    for p in list(monopoly.periods):
        db.session.delete(p)
    db.session.flush()
    metrics = _metrics()
    for year in sorted(data):
        values = {k: v for k, v in data[year].items() if v is not None and k in metrics}
        if not values:
            continue
        period = Period(monopoly_id=monopoly.id, year=year)
        db.session.add(period)
        db.session.flush()
        for code, value in values.items():
            db.session.add(PeriodValue(period_id=period.id, metric_id=metrics[code], value=value))


